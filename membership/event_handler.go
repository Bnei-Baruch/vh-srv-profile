var interestingEvents = map[string]struct{}{
	//orders.TypeCreateAccount: {},
	//orders.TypeUpdateAccount: {},
	//orders.TypeDeleteAccount: {},
	//orders.TypeHardDeleteAccount: {},
	orders.TypeMergeAccount:  {},
	orders.TypeCreateOrder:   {},
	orders.TypeUpdateOrder:   {},
	orders.TypeDeleteOrder:   {},
	orders.TypeCreatePayment: {},
	orders.TypeUpdatePayment: {},
	orders.TypeDeletePayment: {},
	orders.TypeCreateSpecial: {},
	orders.TypeDeleteSpecial: {},
}

var errSkip = errors.New("skip event")

type EventsHandler struct {
	repo          repo.ProfileRepository
	kcTokenSource keycloak.TokenSource
	ordersService orders.OrdersService
}

func NewEventsHandler(repo repo.ProfileRepository) *EventsHandler {
	eh := new(EventsHandler)
	eh.repo = repo
	eh.kcTokenSource = keycloak.NewServiceClient()
	eh.ordersService = orders.NewOrdersAPI()
	return eh
}

func (eh *EventsHandler) HandleOrdersEvent(event orders.Event) {
	ctx := eh.newContext(event)

	// v2 Help Haver requests live in orders; notify the member here so the
	// in-app notification matches v1. These events don't affect membership.
	if event.Type == orders.TypeHHRequestCreated || event.Type == orders.TypeHHRequestConcluded {
		eh.handleHHRequestEvent(ctx, event)
		return
	}

	if eh.shouldSkip(event) {
		return
	}

	var (
		userIDs *repo.EmailKeycloakAndUserIDBody
		err     error
	)

	switch event.Type {
	case orders.TypeMergeAccount:
		userIDs, err = eh.mergeAccounts(ctx, event)
	default:
		userIDs, err = eh.getUserIDs(ctx, event)
	}

	if err != nil {
		if !errors.Is(err, errSkip) {
			utils.LogFor(ctx).Error("membership.EventsHandler.HandleOrdersEvent getUserIDs", slog.Any("err", err))
			sentry.CaptureException(err)
		}
		return
	}

	if userIDs == nil {
		utils.LogFor(ctx).Warn("membership.EventsHandler.HandleOrdersEvent no user IDs",
			slog.String("event_type", event.Type), slog.Any("event_payload", event.Payload))
		sentry.CaptureMessage("membership.EventsHandler.HandleOrdersEvent no user IDs")
		return
	}

	_, err = eh.repo.EvaluateMembershipByUserID(ctx, *userIDs)
	if err != nil {
		utils.LogFor(ctx).Error("membership.EventsHandler.HandleOrdersEvent repo.EvaluateMembershipByUserID", slog.Any("err", err))
		sentry.CaptureException(err)
	}
}

func (eh *EventsHandler) handleHHRequestEvent(ctx context.Context, event orders.Event) {
	kcVal := payloadString(event, "keycloak_id")
	if kcVal == "" {
		utils.LogFor(ctx).Warn("handleHHRequestEvent: missing keycloak_id", slog.Any("payload", event.Payload))
		return
	}

	slug := common.NotificationSlugHHRequestReceived
	if event.Type == orders.TypeHHRequestConcluded {
		approved, ok := event.Payload["approved"].(bool)
		if !ok {
			utils.LogFor(ctx).Warn("handleHHRequestEvent: missing or non-bool 'approved' in concluded event, defaulting to refused",
				slog.Any("payload", event.Payload))
		}
		if approved {
			slug = common.NotificationSlugHHRequestApproved
		} else {
			slug = common.NotificationSlugHHRequestRefused
		}
	}

	if err := eh.repo.NotifyHHRequest(ctx, kcVal, slug); err != nil {
		utils.LogFor(ctx).Error("handleHHRequestEvent: NotifyHHRequest", slog.Any("err", err))
		sentry.CaptureException(err)
	}
}

func (eh *EventsHandler) BuildEvent(eventType string, payload map[string]interface{}) events.Event {
	event := events.MakeEvent(eventType, payload)
	event.Component = events.ComponentMembershipOrdersEventHandler
	event.Actor = events.ActorSystem
	return event
}

func (eh *EventsHandler) newContext(event orders.Event) context.Context {
	logger := slog.Default().With(slog.String("nats_nuid", event.ID))
	ctx := context.WithValue(context.Background(), common.CtxLogger, logger)
	ctx = context.WithValue(ctx, common.CtxTokenSource, eh.kcTokenSource)
	ctx = context.WithValue(ctx, common.CtxEventBuilder, eh)

	hub := sentry.CurrentHub().Clone()
	hub.ConfigureScope(func(scope *sentry.Scope) {
		scope.SetTag("nats_nuid", event.ID)
	})
	ctx = sentry.SetHubOnContext(ctx, hub)

	return ctx
}

func (eh *EventsHandler) shouldSkip(event orders.Event) bool {
	// skip events with no direct impact of membership
	if _, ok := interestingEvents[event.Type]; !ok {
		return true
	}

	// skip events generated by our cron jobs
	if event.Component == orders.ComponentAPI && event.Actor == common.ServiceName {
		return true
	}

	// skip part of robokasa importer chain (account? -> order -> payment)
	if event.Component == orders.ComponentRobokasaImporter && event.Type != orders.TypeCreatePayment {
		return true
	}

	return false
}

func (eh *EventsHandler) getUserIDs(ctx context.Context, event orders.Event) (*repo.EmailKeycloakAndUserIDBody, error) {
	switch event.Type {
	case orders.TypeCreateOrder, orders.TypeUpdateOrder, orders.TypeDeleteOrder:
		orderID, ok := payloadFloat(event, "order_id")
		if !ok {
			return nil, fmt.Errorf("no order_id in %q event", event.Type)
		}
		return eh.getUserIDsFromOrder(ctx, int(orderID))
	case orders.TypeCreatePayment, orders.TypeUpdatePayment, orders.TypeDeletePayment:
		paymentID, ok := payloadFloat(event, "payment_id")
		if !ok {
			return nil, fmt.Errorf("no payment_id in %q event", event.Type)
		}
		return eh.getUserIDsFromPayment(ctx, event, int(paymentID))
	case orders.TypeCreateSpecial, orders.TypeDeleteSpecial:
		ids, err := specialUserIDs(event)
		if err != nil {
			// Expected for a special with no email until vh-srv-orders#39 is
			// deployed: nothing here can act on it, so it is not a Sentry error.
			utils.LogFor(ctx).Warn("membership.EventsHandler: special event without a user",
				slog.String("event_type", event.Type), slog.Any("event_payload", event.Payload), slog.Any("err", err))
			return nil, errSkip
		}
		return ids, nil
	}

	return nil, fmt.Errorf("unsupported event type: %s", event.Type)
}

// specialUserIDs reads the user of a create_special or delete_special event.
// Orders stores an absent identifier as NULL, so either field may be missing,
// null or "" — none of which may panic the consumer, which would lose the
// already-acked event. delete_special carries only email until
// vh-srv-orders#39 is deployed, which adds keycloak_id; until then a special
// with no email cannot be found here.
func specialUserIDs(event orders.Event) (*repo.EmailKeycloakAndUserIDBody, error) {
	email := payloadString(event, "email")
	keycloakID := payloadString(event, "keycloak_id")
	if email == "" && keycloakID == "" {
		return nil, fmt.Errorf("no keycloak_id or email in %q event", event.Type)
	}

	ret := repo.EmailKeycloakAndUserIDBody{}
	if email != "" {
		ret.Email = &email
	}
	if keycloakID != "" {
		ret.KeycloakID = &keycloakID
	}
	return &ret, nil
}

func (eh *EventsHandler) mergeAccounts(ctx context.Context, event orders.Event) (*repo.EmailKeycloakAndUserIDBody, error) {
	sourceID := payloadString(event, "source_account_id")
	destinationID := payloadString(event, "destination_account_id")
	if sourceID == "" || destinationID == "" {
		return nil, fmt.Errorf("EventsHandler.mergeAccounts: no source_account_id or destination_account_id in %q event", event.Type)
	}
	var mergeData = repo.AccountsMergeData{
		SourceId:      sourceID,
		DestinationId: destinationID,
	}
	res, err := eh.repo.MergeAccounts(ctx, mergeData)
	if err != nil {
		return nil, fmt.Errorf("EventsHandler.mergeAccounts: %w", err)
	}
	return res, nil

}

func (eh *EventsHandler) getUserIDsFromOrder(ctx context.Context, orderID int) (*repo.EmailKeycloakAndUserIDBody, error) {
	order, err := eh.ordersService.GetOrderByID(ctx, orderID)
	if err != nil {
		return nil, fmt.Errorf("ordersService.GetOrderByID: %w", err)
	}

	account, err := eh.ordersService.GetAccountByID(ctx, order.AccountID)
	if err != nil {
		return nil, fmt.Errorf("ordersService.GetAccountByID: %w", err)
	}

	return &repo.EmailKeycloakAndUserIDBody{
		Email:      &account.Email,
		KeycloakID: &account.UserKey,
	}, nil
}

func (eh *EventsHandler) getUserIDsFromPayment(ctx context.Context, event orders.Event, paymentID int) (*repo.EmailKeycloakAndUserIDBody, error) {
	payment, err := eh.ordersService.GetPaymentByID(ctx, paymentID)
	if err != nil {
		return nil, fmt.Errorf("ordersService.GetPaymentByID: %w", err)
	}

	if event.Type == orders.TypeCreatePayment && payment.PaymentStatus == "pending" {
		return nil, errSkip
	}

	return eh.getUserIDsFromOrder(ctx, payment.OrderID)
}

// payloadString reads a string field of an orders event; missing, null and a
// non-string value all read as "". Payload fields are never asserted
// unchecked: a panic would lose the already-acked event.
func payloadString(event orders.Event, key string) string {
	s, _ := event.Payload[key].(string)
	return s
}

// payloadFloat reads a JSON number field of an orders event.
func payloadFloat(event orders.Event, key string) (float64, bool) {
	f, ok := event.Payload[key].(float64)
	return f, ok
}
